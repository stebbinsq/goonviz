#!/usr/bin/env python3
"""Pack presets, shaders, palettes, knob definitions and MIDI maps into web/bundle.js.

The web app (web/index.html) loads this one file instead of fetching, which is
what lets it run straight from disk (file://) in Chrome. Re-run after editing
presets, shaders, palettes, params or maps:

    python3 tools/build_web.py
"""

import glob
import hashlib
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from prism.params import PARAM_DEFS, KALEIDO_CHAOS  # noqa: E402
from prism.palettes import PALETTES  # noqa: E402
from prism.midi import STATE_ACTIONS, MMC_COMMANDS, MOMENTARY  # noqa: E402
from prism.app import ACTION_ITEMS  # noqa: E402


def read(path):
    with open(os.path.join(ROOT, path)) as f:
        return f.read()


def main():
    presets = [{"key": os.path.splitext(os.path.basename(p))[0], "source": read(p)}
               for p in sorted(glob.glob(os.path.join(ROOT, "presets", "*.glsl")))]
    maps = {os.path.splitext(os.path.basename(p))[0]: json.loads(read(p))
            for p in sorted(glob.glob(os.path.join(ROOT, "maps", "*.json")))}
    data = {
        "shaders": {name: read(f"prism/shaders/{name}.glsl")
                    for name in ("lib", "scene_header", "composite", "display")},
        "presets": presets,
        "params": [{"name": n, "lo": lo, "hi": hi, "default": d, **opts} for n, lo, hi, d, opts in PARAM_DEFS],
        "kaleidoChaos": KALEIDO_CHAOS,
        "palettes": [{"name": n, "colors": c} for n, c in PALETTES],
        "maps": maps,
        "actions": ACTION_ITEMS,
        "stateActions": sorted(STATE_ACTIONS),
        "momentary": sorted(MOMENTARY),
        "mmc": {str(k): v for k, v in MMC_COMMANDS.items()},
    }
    out = os.path.join(ROOT, "web", "bundle.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("// Generated by tools/build_web.py: edit the presets/ and prism/ sources, then re-run it.\n")
        f.write("window.PRISM_DATA = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {out}: {len(presets)} presets, {len(maps)} maps")
    stamp_scripts()
    sheet = os.path.join(ROOT, "docs", "akai_mpd32_cheatsheet.pdf")
    if os.path.exists(sheet):
        shutil.copy(sheet, os.path.join(ROOT, "web", "cheatsheet.pdf"))


def stamp_scripts():
    """Add ?v=<hash> to every script in index.html so browsers never mix old and new files after a deploy
    (GitHub Pages lets browsers cache for 10 minutes)."""
    web = os.path.join(ROOT, "web")
    files = [os.path.join(web, "bundle.js")] + sorted(glob.glob(os.path.join(web, "js", "*.js")))
    digest = hashlib.sha1(b"".join(open(f, "rb").read() for f in files)).hexdigest()[:10]
    index = os.path.join(web, "index.html")
    with open(index) as f:
        page = f.read()
    page = re.sub(r'src="((?:bundle|js/[\w-]+)\.js)(?:\?v=\w+)?"', rf'src="\1?v={digest}"', page)
    with open(index, "w") as f:
        f.write(page)


if __name__ == "__main__":
    main()
